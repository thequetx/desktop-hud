// Writes THIRD_PARTY_NOTICES.md from the licence files of what ships (Phase 9.7).
//
// What ships: the main process's runtime dependencies (package.json
// `dependencies`), what Vite bundles into the pages (React, yaml), the
// bundled fonts, and Electron itself (whose installer also carries Chromium's
// own notices, LICENSES.chromium.html). `--check` fails when the file is out
// of date, or when a shipped package's licence isn't on the allowed list.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');

/** Licences compatible with shipping inside an MIT app. MPL-2.0 is file-level
 *  copyleft: fine unmodified, with its notice and a pointer to its source. */
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', 'OFL-1.1', 'MPL-2.0', '0BSD']);

const pkg = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const SHIPPED = [
  ...Object.keys(pkg.dependencies || {}).map((name) => ({ name, why: 'main process' })),
  { name: 'react', why: 'bundled into the pages' },
  { name: 'react-dom', why: 'bundled into the pages' },
  { name: 'scheduler', why: 'bundled into the pages (react-dom)' },
  { name: 'yaml', why: 'bundled into the pages' },
  { name: '@fontsource/barlow', why: 'bundled font' },
  { name: '@fontsource/rajdhani', why: 'bundled font' },
  { name: 'electron', why: 'the runtime (Chromium’s notices ship as LICENSES.chromium.html)' },
];

function licenceText(dir) {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying|ofl)(\.|$)/i.test(n));
  return f ? readFileSync(path.join(dir, f), 'utf8').trim() : null;
}

const problems = [];
const parts = [
  '# Third-party notices',
  '',
  'Desktop HUD is MIT-licensed (see LICENSE). It includes the software below, each under its own licence.',
  '',
  'Generated by `node scripts/notices.mjs`; do not edit by hand.',
  '',
];
for (const { name, why } of SHIPPED) {
  const dir = path.join(ROOT, 'node_modules', name);
  if (!existsSync(dir)) {
    problems.push(`${name}: not installed`);
    continue;
  }
  const meta = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const licence = typeof meta.license === 'string' ? meta.license : 'unknown';
  if (!ALLOWED.has(licence)) problems.push(`${name}: licence ${licence} is not on the allowed list`);
  const text = licenceText(dir);
  if (!text) problems.push(`${name}: no licence file`);
  const home = meta.homepage || (meta.repository && (meta.repository.url || meta.repository)) || '';
  parts.push(`## ${name} ${meta.version}`, '', `${licence}. ${why}.${home ? ` Source: ${String(home).replace(/^git\+/, '')}` : ''}`, '', '```', text || '(licence file missing)', '```', '');
}
const out = `${parts.join('\n').trim()}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) problems.push('THIRD_PARTY_NOTICES.md is out of date: run node scripts/notices.mjs');
  if (problems.length) {
    console.error(`[notices] ${problems.join('\n[notices] ')}`);
    process.exit(1);
  }
  console.log(`[notices] up to date; ${SHIPPED.length} packages, all on the allowed licence list`);
} else {
  writeFileSync(OUT, out);
  if (problems.length) {
    console.error(`[notices] ${problems.join('\n[notices] ')}`);
    process.exit(1);
  }
  console.log(`[notices] wrote THIRD_PARTY_NOTICES.md (${SHIPPED.length} packages)`);
}
